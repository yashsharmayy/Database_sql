-- inner join


SELECT
	D.DEPARTMENT_ID,
	D.DEPARTMENT_NAME,
	E.EMPLOYEE_NAME,
	E.SALARY,
	E.DEPARTMENT_ID
FROM
	DEPARTMENTS AS D
	INNER JOIN EMPLOYEES AS E ON D.DEPARTMENT_ID = E.DEPARTMENT_ID;


-- left join

SELECT
	D.DEPARTMENT_ID,
	D.DEPARTMENT_NAME,
	E.EMPLOYEE_NAME,
	E.SALARY,
	E.DEPARTMENT_ID
FROM
	DEPARTMENTS AS D
	LEFT JOIN EMPLOYEES AS E ON D.DEPARTMENT_ID = E.DEPARTMENT_ID;


	-- RIGHT join

SELECT
	D.DEPARTMENT_ID,
	D.DEPARTMENT_NAME,
	E.EMPLOYEE_NAME,
	E.SALARY,
	E.DEPARTMENT_ID
FROM
	DEPARTMENTS AS D
	RIGHT JOIN EMPLOYEES AS E ON D.DEPARTMENT_ID = E.DEPARTMENT_ID;

	-- FULL join

SELECT
	D.DEPARTMENT_ID,
	D.DEPARTMENT_NAME,
	E.EMPLOYEE_NAME,
	E.SALARY,
	E.DEPARTMENT_ID
FROM
	DEPARTMENTS AS D
	FULL JOIN EMPLOYEES AS E ON D.DEPARTMENT_ID = E.DEPARTMENT_ID;


-- CROSS JOIN
	SELECT
	D.DEPARTMENT_ID,
	D.DEPARTMENT_NAME,
	E.EMPLOYEE_NAME,
	E.SALARY,
	E.DEPARTMENT_ID
FROM
	DEPARTMENTS AS D
	CROSS JOIN EMPLOYEES AS E;

-- SELF JOIN

SELECT E1.EMPLOYEE_NAME,
	E1.SALARY,
	E1.DEPARTMENT_ID,
	E2.EMPLOYEE_NAME,
	E2.SALARY,
	E2.DEPARTMENT_ID
	FROM EMPLOYEES AS E1
	JOIN EMPLOYEES AS E2
	ON E1.DEPARTMENT_ID = E2.DEPARTMENT_ID
	AND E1.EMPLOYEE_NAME != E2.EMPLOYEE_NAME;



-- Beginner
-- 1. Display employee names with their department names.

SELECT
	E.EMPLOYEE_NAME,
	D.DEPARTMENT_NAME
FROM
	EMPLOYEES AS E
	JOIN DEPARTMENTS AS D ON E.DEPARTMENT_ID = D.DEPARTMENT_ID;
	
-- 2. Display all employees, including those without a department.

SELECT
	E.EMPLOYEE_NAME,
	D.DEPARTMENT_NAME
FROM
	EMPLOYEES AS E
	LEFT JOIN DEPARTMENTS AS D ON E.DEPARTMENT_ID = D.DEPARTMENT_ID;

-- 3. Display all departments, including those without employees.

SELECT
	E.EMPLOYEE_NAME,
	D.DEPARTMENT_NAME
FROM
	EMPLOYEES AS E
	RIGHT JOIN DEPARTMENTS AS D ON E.DEPARTMENT_ID = D.DEPARTMENT_ID;

-- Intermediate
-- 4. Find the total number of employees in each department.

SELECT
	COUNT(E.EMPLOYEE_ID) AS TOTAL_EMPLOYEES,
	D.DEPARTMENT_NAME
FROM
	EMPLOYEES AS E
	JOIN DEPARTMENTS AS D ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
GROUP BY
	D.DEPARTMENT_NAME;

-- 5. Find the total salary of each department.

SELECT
	SUM(E.SALARY) AS TOTAL_SALARY,
	D.DEPARTMENT_NAME
FROM
	EMPLOYEES AS E
	JOIN DEPARTMENTS AS D ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
GROUP BY
	D.DEPARTMENT_NAME;

	
-- 6. Display department names with their project names.

SELECT D.DEPARTMENT_NAME , P.PROJECT_NAME
FROM DEPARTMENTS AS D
JOIN
PROJECTS AS P
ON D.DEPARTMENT_ID = P.DEPARTMENT_ID;

-- 7. Find departments that have no employees.

SELECT
	D.DEPARTMENT_NAME,
	E.EMPLOYEE_NAME
FROM
	DEPARTMENTS AS D
	LEFT JOIN EMPLOYEES AS E ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
WHERE
	E.EMPLOYEE_ID IS NULL;