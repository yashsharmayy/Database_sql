-- inner join


SELECT
	D.DEPARTMENT_ID,
	D.DEPARTMENT_NAME,
	E.EMPLOYEE_NAME,
	E.SALARY,
	E.DEPARTMENT_ID
FROM
	DEPARTMENTS AS D
	INNER JOIN EMPLOYEES AS E ON D.DEPARTMENT_ID = E.DEPARTMENT_ID;


-- left join

SELECT
	D.DEPARTMENT_ID,
	D.DEPARTMENT_NAME,
	E.EMPLOYEE_NAME,
	E.SALARY,
	E.DEPARTMENT_ID
FROM
	DEPARTMENTS AS D
	LEFT JOIN EMPLOYEES AS E ON D.DEPARTMENT_ID = E.DEPARTMENT_ID;


	-- RIGHT join

SELECT
	D.DEPARTMENT_ID,
	D.DEPARTMENT_NAME,
	E.EMPLOYEE_NAME,
	E.SALARY,
	E.DEPARTMENT_ID
FROM
	DEPARTMENTS AS D
	RIGHT JOIN EMPLOYEES AS E ON D.DEPARTMENT_ID = E.DEPARTMENT_ID;

	-- FULL join

SELECT
	D.DEPARTMENT_ID,
	D.DEPARTMENT_NAME,
	E.EMPLOYEE_NAME,
	E.SALARY,
	E.DEPARTMENT_ID
FROM
	DEPARTMENTS AS D
	FULL JOIN EMPLOYEES AS E ON D.DEPARTMENT_ID = E.DEPARTMENT_ID;


-- CROSS JOIN
	SELECT
	D.DEPARTMENT_ID,
	D.DEPARTMENT_NAME,
	E.EMPLOYEE_NAME,
	E.SALARY,
	E.DEPARTMENT_ID
FROM
	DEPARTMENTS AS D
	CROSS JOIN EMPLOYEES AS E;

-- SELF JOIN

SELECT E1.EMPLOYEE_NAME,
	E1.SALARY,
	E1.DEPARTMENT_ID,
	E2.EMPLOYEE_NAME,
	E2.SALARY,
	E2.DEPARTMENT_ID
	FROM EMPLOYEES AS E1
	JOIN EMPLOYEES AS E2
	ON E1.DEPARTMENT_ID = E2.DEPARTMENT_ID
	AND E1.EMPLOYEE_NAME != E2.EMPLOYEE_NAME;



